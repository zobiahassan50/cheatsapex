/**
 * Writes public/_redirects from the single-hop PATH_REDIRECTS map + checkout 302s.
 * Run before deploy / as part of build so Cloudflare never sees stale multi-hop rules.
 */
import fs from 'node:fs';
import path from 'node:path';
import { PATH_REDIRECTS, auditRedirectGraph } from './redirects.mjs';
import { CHECKOUT_PATH_REDIRECTS } from '../src/config/checkout-redirects.mjs';

const root = process.cwd();
const outFile = path.join(root, 'public', '_redirects');

const issues = auditRedirectGraph();
const loops = issues.filter((i) => i.type === 'loop');
const chains = issues.filter((i) => i.type === 'chain');
if (loops.length) {
  console.error('Redirect loops detected:', loops);
  process.exit(1);
}
if (chains.length) {
  console.error('Multi-hop redirect chains (must be single-hop):', chains);
  process.exit(1);
}

const lines = [
  '# Generated by scripts/sync-public-redirects.mjs — do not hand-edit.',
  '# Checkout (same-tab 302 → Levo Apex)',
];

for (const [from, url] of CHECKOUT_PATH_REDIRECTS) {
  lines.push(`${from}  ${url}  302`);
}

lines.push('', '# Static path redirects (301, single-hop finals only)');

/** Prefer unique from→to pairs; include both slash variants already in the Map. */
const seen = new Set();
const sorted = [...PATH_REDIRECTS.entries()].sort((a, b) => a[0].localeCompare(b[0]));
for (const [from, to] of sorted) {
  const key = `${from}→${to}`;
  if (seen.has(key)) continue;
  seen.add(key);
  lines.push(`${from}  ${to}  301`);
}

lines.push('');
fs.writeFileSync(outFile, lines.join('\n'), 'utf8');
console.log(`Wrote ${seen.size} redirect rules → ${path.relative(root, outFile)}`);
